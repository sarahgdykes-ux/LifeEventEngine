"use client";

import { useEffect, useRef, useState } from "react";
import DecisionForm from "@/components/decision-form";
import SimulationReportView from "@/components/simulation-report-view";
import type { DecisionInput } from "@/lib/schemas/decision";
import { SimulationApiErrorSchema } from "@/lib/schemas/api";
import { SimulationReportSchema, type SimulationReport } from "@/lib/schemas/simulation";

interface StoredDecision {
  id: string;
  question: string;
  timestamp: number;
  decision: DecisionInput;
}

type RequestErrorKind = "validation" | "server" | "network" | "response";

interface RequestError {
  kind: RequestErrorKind;
  message: string;
}

class SimulationRequestError extends Error {
  constructor(readonly kind: RequestErrorKind, message: string) {
    super(message);
  }
}

const ERROR_TITLES: Record<RequestErrorKind, string> = {
  validation: "Check your decision details",
  server: "The simulation could not finish",
  network: "Connection problem",
  response: "Unexpected response",
};

export default function SimulationApp() {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<RequestError | null>(null);
  const [report, setReport] = useState<SimulationReport | null>(null);
  const [reportedDecision, setReportedDecision] = useState<DecisionInput | null>(null);
  const [loadingStage, setLoadingStage] = useState(0);
  const [decisionHistory, setDecisionHistory] = useState<StoredDecision[]>([]);
  const [showHistoryDropdown, setShowHistoryDropdown] = useState(false);
  const submissionInProgress = useRef(false);
  const reportColumnRef = useRef<HTMLDivElement>(null);

  const LOADING_STAGES = [
    { agent: "Optimist", icon: "☀️", message: "Optimist is thinking..." },
    { agent: "Pessimist", icon: "☁️", message: "Pessimist is considering risks..." },
    { agent: "Financial", icon: "💰", message: "Financial agent is running numbers..." },
    { agent: "Wellbeing", icon: "❤️", message: "Wellbeing specialist is reflecting..." },
  ];

  const HISTORY_STORAGE_KEY = "life-decision-history";
  const MAX_HISTORY_ITEMS = 20;

  useEffect(() => {
    try {
      const stored = localStorage.getItem(HISTORY_STORAGE_KEY);
      if (stored) {
        const parsed = JSON.parse(stored) as StoredDecision[];
        setDecisionHistory(parsed);
      }
    } catch {
      // If localStorage fails, just start with empty history
    }
  }, []);

  function saveToHistory(decision: DecisionInput) {
    const newEntry: StoredDecision = {
      id: crypto.randomUUID(),
      question: decision.question,
      timestamp: Date.now(),
      decision,
    };

    const updatedHistory = [newEntry, ...decisionHistory].slice(0, MAX_HISTORY_ITEMS);
    setDecisionHistory(updatedHistory);

    try {
      localStorage.setItem(HISTORY_STORAGE_KEY, JSON.stringify(updatedHistory));
    } catch {
      // Silently fail if localStorage is full or unavailable
    }
  }

  function loadFromHistory(entry: StoredDecision) {
    setReport(null);
    setReportedDecision(null);
    setError(null);
    setShowHistoryDropdown(false);
    // Pass the stored decision to the form via a callback (need to add this to DecisionForm)
  }

  function clearHistory() {
    setDecisionHistory([]);
    try {
      localStorage.removeItem(HISTORY_STORAGE_KEY);
    } catch {
      // Silently fail
    }
  }

  function handleEditAndRerun() {
    setReport(null);
    setReportedDecision(null);
    setError(null);
  }

  function handleCopyReport() {
    if (!report || !reportedDecision) return;

    const text = `
Decision: ${reportedDecision.question}

Option A: ${reportedDecision.options[0].label}
${reportedDecision.options[0].description ? reportedDecision.options[0].description : ''}

Option B: ${reportedDecision.options[1].label}
${reportedDecision.options[1].description ? reportedDecision.options[1].description : ''}

Goals: ${reportedDecision.goals.join(', ')}
Priorities: ${reportedDecision.priorities.join(', ')}

This report is generated by the Life Decision Simulator for reflection purposes only, not as predictions or recommendations.
    `.trim();

    navigator.clipboard.writeText(text).then(() => {
      // Could add a toast notification here
    }).catch(() => {
      // Silently fail if clipboard API fails
    });
  }

  function handlePrintReport() {
    window.print();
  }

  useEffect(() => {
    if (report && reportedDecision && window.innerWidth < 900) {
      reportColumnRef.current?.scrollIntoView({ behavior: "smooth", block: "start" });
    }
  }, [report, reportedDecision]);

  async function submitDecision(decision: DecisionInput) {
    if (submissionInProgress.current) return;
    submissionInProgress.current = true;
    setLoading(true);
    setLoadingStage(0);
    setError(null);
    setReport(null);
    setReportedDecision(null);

    // Animate through loading stages
    for (let i = 0; i < LOADING_STAGES.length; i++) {
      await new Promise(resolve => setTimeout(resolve, 800));
      setLoadingStage(i + 1);
    }

    try {
      const response = await fetch("/api/simulate", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(decision),
      });

      let payload: unknown;
      try {
        payload = await response.json();
      } catch {
        if (response.status >= 500) {
          throw new SimulationRequestError("server", `The server returned an error (${response.status}). Please try again.`);
        }
        throw new SimulationRequestError(
          response.ok ? "response" : "validation",
          response.ok
            ? "The simulation returned an unreadable response. Please try again."
            : "The request could not be validated. Check required fields and keep text within the documented limits.",
        );
      }

      if (!response.ok) {
        const apiError = SimulationApiErrorSchema.safeParse(payload);
        if (response.status === 413) {
          throw new SimulationRequestError(
            "validation",
            "Decision details exceed the request size limit. Shorten the text or remove list items and try again.",
          );
        }
        if (response.status === 400 || (apiError.success && apiError.data.error.code === "INVALID_REQUEST")) {
          throw new SimulationRequestError(
            "validation",
            "The request could not be validated. Check required fields and keep text within the documented limits.",
          );
        }
        throw new SimulationRequestError(
          response.status >= 500 ? "server" : "validation",
          response.status >= 500
            ? "The simulation is temporarily unavailable. Please try again."
            : "The request could not be validated. Check required fields and keep text within the documented limits.",
        );
      }

      const parsedReport = SimulationReportSchema.safeParse(payload);
      if (!parsedReport.success) {
        throw new SimulationRequestError("response", "The simulation returned an unexpected report. Please try again.");
      }

      setReport(parsedReport.data);
      setReportedDecision(decision);
      saveToHistory(decision);
    } catch (caught: unknown) {
      if (caught instanceof SimulationRequestError) {
        setError({ kind: caught.kind, message: caught.message });
      } else if (caught instanceof TypeError) {
        setError({
          kind: "network",
          message: "Could not connect to the simulation. Check your connection and try again.",
        });
      } else {
        setError({
          kind: "server",
          message: "Something went wrong while preparing the simulation. Please try again.",
        });
      }
    } finally {
      submissionInProgress.current = false;
      setLoading(false);
      setLoadingStage(0);
    }
  }

  return (
    <main className="site-shell">
      <header className="topbar">
        <a className="wordmark" href="/" aria-label="Life Decision Simulator home">
          <span className="wordmark-mark" aria-hidden="true">L</span>
          <span>Life Decision<br />Simulator</span>
        </a>
        <span className="topbar-note"><span className="status-dot" /> Prototype · decision exploration</span>
      </header>

      <section className="intro" aria-labelledby="page-title">
        <p className="eyebrow">MAKE SPACE FOR WHAT MATTERS</p>
        <h1 id="page-title">See both paths<br className="desktop-break" /> more clearly.</h1>
        <p className="intro-copy">Explore possible outcomes from two paths, using your goals and priorities as context. This prototype offers reflection prompts—not predictions or recommendations.</p>
      </section>

      <div className="workspace">
        <section className="input-column" aria-labelledby="form-title">
          <div className="section-heading">
            <span className="step-number">01</span>
            <div>
              <h2 id="form-title">Your decision</h2>
              <p>Start with the question and the two options in front of you.</p>
            </div>
          </div>
          {error && <div className="error-panel" role="alert"><span className="error-symbol" aria-hidden="true">!</span><div><h3>{ERROR_TITLES[error.kind]}</h3><p>{error.message}</p></div></div>}
          {decisionHistory.length > 0 && (
            <div className="history-section">
              <div className="history-dropdown-container">
                <button
                  className="history-toggle"
                  onClick={() => setShowHistoryDropdown(!showHistoryDropdown)}
                  aria-expanded={showHistoryDropdown}
                >
                  <span>Recent decisions</span>
                  <span className="history-count">{decisionHistory.length}</span>
                </button>
                {showHistoryDropdown && (
                  <div className="history-dropdown">
                    <ul className="history-list">
                      {decisionHistory.slice(0, 5).map((entry) => (
                        <li key={entry.id}>
                          <button
                            className="history-item"
                            onClick={() => loadFromHistory(entry)}
                          >
                            <span className="history-question">{entry.question}</span>
                            <span className="history-date">
                              {new Date(entry.timestamp).toLocaleDateString()}
                            </span>
                          </button>
                        </li>
                      ))}
                    </ul>
                    <button
                      className="history-clear"
                      onClick={clearHistory}
                    >
                      Clear history
                    </button>
                  </div>
                )}
              </div>
            </div>
          )}
          <DecisionForm loading={loading} onSubmit={submitDecision} initialData={reportedDecision || undefined} />
        </section>

        <section className="report-column" ref={reportColumnRef} aria-labelledby="report-column-title" aria-busy={loading}>
          <div className="section-heading report-heading">
            <span className="step-number step-number-alt">02</span>
            <div>
              <h2 id="report-column-title">Your perspective report</h2>
              <p>What might each path make possible?</p>
            </div>
          </div>
          <div aria-live="polite" aria-atomic="true">
            {loading ? (
              <div className="loading-panel" role="status">
                <div className="loading-animation">
                  {LOADING_STAGES.map((stage, index) => (
                    <div
                      key={stage.agent}
                      className={`loading-stage ${index < loadingStage ? "loading-stage-complete" : ""} ${index === loadingStage ? "loading-stage-active" : ""}`}
                    >
                      <span className="loading-icon" aria-hidden="true">{stage.icon}</span>
                      <span className="loading-message">{stage.message}</span>
                    </div>
                  ))}
                </div>
                <div className="loading-footer">
                  <span className="loading-spinner" aria-hidden="true" />
                  <div><h3>Preparing both perspectives</h3><p>Eight specialist analyses are being prepared. This can take a moment; the scenarios are illustrative, not predictions.</p></div>
                </div>
              </div>
            ) : report && reportedDecision ? (
              <>
                <SimulationReportView report={report} decision={reportedDecision} />
                <div className="report-actions">
                  <button className="action-button" onClick={handleCopyReport} type="button">
                    Copy report
                  </button>
                  <button className="action-button" onClick={handlePrintReport} type="button">
                    Print report
                  </button>
                  <button className="edit-button" onClick={handleEditAndRerun} type="button">
                    Edit and re-run
                  </button>
                </div>
              </>
            ) : (
              <div className="empty-report">
                <div className="empty-preview" aria-hidden="true">
                  <div className="preview-section">
                    <div className="preview-header">
                      <span className="preview-badge">Complete report</span>
                      <h4 className="preview-question">Should I pursue graduate school or move to a new city?</h4>
                    </div>
                    <div className="preview-timeline">
                      <div className="preview-timeline-column">
                        <span className="preview-year">Year 1</span>
                        <div className="preview-perspective"><span>☀️</span> Early exploration</div>
                        <div className="preview-perspective"><span>☁️</span> Monitor setbacks</div>
                        <div className="preview-perspective"><span>💰</span> Transition costs</div>
                        <div className="preview-perspective"><span>❤️</span> Stress levels</div>
                      </div>
                      <div className="preview-timeline-column">
                        <span className="preview-year">Year 5</span>
                        <div className="preview-perspective"><span>☀️</span> New paths</div>
                        <div className="preview-perspective"><span>☁️</span> Room for goals</div>
                        <div className="preview-perspective"><span>💰</span> Income check</div>
                        <div className="preview-perspective"><span>❤️</span> Routine fit</div>
                      </div>
                      <div className="preview-timeline-column">
                        <span className="preview-year">Year 10</span>
                        <div className="preview-perspective"><span>☀️</span> Life story</div>
                        <div className="preview-perspective"><span>☁️</span> Stay flexible</div>
                        <div className="preview-perspective"><span>💰</span> Savings check</div>
                        <div className="preview-perspective"><span>❤️</span> Alignment</div>
                      </div>
                    </div>
                  </div>
                </div>
                <div className="empty-content">
                  <h3>A little clarity starts here.</h3>
                  <p>Enter your decision and submit the form to compare perspectives for both options.</p>
                  <span className="empty-footnote">Exploratory scores, not predictions.</span>
                </div>
              </div>
            )}
          </div>
        </section>
      </div>

      <footer className="page-footer"><span>For reflection, not decision advice.</span><span>Explore possibilities—not predictions.</span></footer>
    </main>
  );
}